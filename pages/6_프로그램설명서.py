import streamlit as st

from core.auth import ensure_login
from core.bootstrap import initialize_app

initialize_app()
ensure_login()
st.title('프로그램 설명서')
st.caption('현재 프로그램 구조와 실제 동작 기준으로 정리한 설명서입니다.')

st.markdown(
    '''
### 1. app
- 홈 화면입니다.
- **지금 실행** 버튼을 누르면 우리 상품 최신 가격을 조회하고, 저장된 경쟁사 가격과 비교합니다.
- 화면 아래의 **우리 상품 설정**에서 상품명, 상품 ID, 검색어, 사용 여부, 정렬순서를 직접 관리합니다.
- 우리 상품 조회 순서는 **상품 ID 우선 → 실패/미등록 시 검색어** 입니다.
'''
)
st.info('고정 IP 중계 서버 모드로 네이버 커머스 API에 연결됩니다.')

st.markdown(
    '''
### 2. 실행 결과
- 최근 저장된 실행 결과를 선택해서 확인합니다.
- 이전 실행과 비교해 가격이 얼마나 달라졌는지도 함께 표시합니다.
- 경쟁사 가격이 아직 없는 상품은 실행 결과에서 빈칸으로 보일 수 있습니다.

### 3. 경쟁사 가격 입력
- 경쟁사 가격을 한 번에 붙여넣어 저장합니다.
- 저장된 경쟁사 가격은 **수동 실행**과 **매일 Cron 실행**에서 그대로 사용됩니다.
- 상품명 앞의 `*`는 있어도 되고 없어도 됩니다.
- 가격 줄의 `-`도 숫자를 입력할 때는 없어도 됩니다.
  - 예: `그린팜 - 55,000`, `그린팜 55,000` 둘 다 가능
- 상품 구분은 `우리 상품 설정`에 등록한 상품명으로 자동 인식합니다.
- 쇼핑몰 구분은 `쇼핑몰 설정`에 등록한 쇼핑몰명/표시쇼핑몰명으로 자동 인식합니다.
- `우리 - 40,000`처럼 우리 가격 줄을 적어도 저장하지 않고 무시합니다.
- `야채이야기 -`처럼 가격을 비워 입력하면 해당 경쟁사 가격만 삭제합니다.
'''
)
st.info(
    '`우리 - 가격` 줄은 입력해도 무시합니다. 경쟁사 가격만 저장됩니다. '
    '일부 상품/일부 경쟁사만 입력하면 적어 둔 값만 수정되고 나머지는 기존 값이 유지됩니다. '
    '`야채이야기 -`처럼 가격을 비워서 저장하면 해당 경쟁사 가격만 삭제됩니다.'
)

st.markdown(
    '''
### 4. 가격 규칙
- 단위 환산이 필요한 경우 `mul`, `add`, `sub`, `set`, `rate` 규칙을 사용합니다.
- 입력한 경쟁사 가격에도 저장 후 결과 계산 시 동일하게 규칙이 적용됩니다.

### 5. 쇼핑몰 설정
- 쇼핑몰명, 표시 쇼핑몰명, 사용 여부, 정렬순서를 수정합니다.
- 경쟁사 가격 일괄 입력에서는 **표시 쇼핑몰명**도 함께 인식합니다.

### 6. 자동 실행
- Cron은 **한국시간 매일 오전 7시 50분**에 실행됩니다.
- Cron은 **우리 가격만 네이버 API로 최신화**합니다.
- 경쟁사 가격은 사용자가 마지막으로 저장한 값을 그대로 사용합니다.
- 실행 결과는 텔레그램으로 발송됩니다.

### 7. 입력 팁
- 상품 사이 빈 줄은 **있어도 되고 없어도 됩니다.**
- 한 상품에서 한 쇼핑몰만 적어도 됩니다.
- 일부 상품만 다시 입력하면 **적은 부분만 수정**되고 나머지는 유지됩니다.
- 별표 없이 상품명을 쓰려면 `우리 상품 설정`에 그 상품이 등록되어 있어야 합니다.
'''
)
