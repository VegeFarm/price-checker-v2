import streamlit as st

from core.auth import ensure_login
from core.bootstrap import initialize_app

initialize_app()
ensure_login()
st.title('프로그램 설명서')
st.caption('현재 프로그램 구조와 실제 동작 기준으로 정리한 설명서입니다.')

st.markdown(
    '''
### 1. app
- 홈 화면입니다.
- **지금 실행** 버튼을 누르면 우리 상품 최신 가격을 조회하고, 저장된 경쟁사 가격과 비교합니다.
- 우리 상품 가격은 네이버 커머스 API에서 가져옵니다.
- 고정 IP 중계 서버를 통해 네이버 커머스 API에 연결합니다.
'''
)

st.markdown(
    '''
### 2. 실행 결과
- 최근 저장된 실행 결과를 선택해서 확인합니다.
- 이전 실행과 비교해 가격이 얼마나 달라졌는지도 함께 표시합니다.
- 경쟁사 가격이 아직 없는 상품은 `쇼핑몰명 -` 형태로 표시됩니다.

### 3. 경쟁사 가격 입력
- 경쟁사 가격을 한 번에 붙여넣어 저장합니다.
- 저장된 경쟁사 가격은 **app과 실행 결과에 즉시 반영**되며, 다음 수동 실행과 Cron 실행에서도 그대로 사용됩니다.
- 상품명 앞의 `*`는 있어도 되고 없어도 됩니다.
- 가격 줄의 `-`도 숫자를 입력할 때는 없어도 됩니다.
  - 예: `그린팜 - 55,000`, `그린팜 55,000` 둘 다 가능
- 상품 사이 빈 줄은 있어도 되고 없어도 됩니다.
- 한 상품에서 한 쇼핑몰 가격만 적어도 됩니다.
- 일부 상품/일부 경쟁사만 다시 입력하면 적은 부분만 수정되고 나머지는 기존 값이 유지됩니다.
- `우리 - 40,000`처럼 우리 가격 줄을 적어도 저장하지 않고 무시합니다.
- `야채이야기 -`처럼 가격을 비워 입력하면 해당 경쟁사 가격만 삭제하며, app과 실행 결과에서도 `야채이야기 -`로 표시됩니다.
- 별표 없이 상품명을 입력하려면 **검색상품설정**에 해당 상품이 등록되어 있어야 합니다.

### 4. 검색상품설정
- 네이버에서 조회할 우리 상품을 관리합니다.
- 상품 ID가 등록되어 있으면 상품 ID를 먼저 사용합니다.
- 상품 ID가 없거나 ID로 상품을 찾지 못하면 검색어를 사용합니다.
- 상품명, 상품 ID, 검색어, 사용 여부, 정렬순서를 수정할 수 있습니다.

### 5. 가격 규칙
- 단위 환산이 필요한 경우 `mul`, `add`, `sub`, `set`, `rate` 규칙을 사용합니다.
- 경쟁사 수동 가격은 입력한 최종 비교 가격을 그대로 사용합니다.

### 6. 쇼핑몰 설정
- 쇼핑몰명, 표시 쇼핑몰명, 사용 여부, 정렬순서를 수정합니다.

### 7. 자동 실행
- Cron은 **한국시간 매일 오전 7시 50분**에 실행됩니다.
- Cron은 **우리 가격만 네이버 API로 최신화**합니다.
- 경쟁사 가격은 사용자가 마지막으로 저장한 값을 그대로 사용합니다.
- 실행 결과는 텔레그램으로 발송됩니다.
'''
)
