import streamlit as st

from core.auth import ensure_login
from core.bootstrap import initialize_app

initialize_app()
ensure_login()
st.title('프로그램 설명서')
st.markdown(
    """
### 가격 수집 방식
- **우리(채소팜)** 가격만 네이버 커머스 API에서 가져옵니다.
- **경쟁사** 가격은 `경쟁사 가격 입력`에서 직접 저장한 최신 가격을 사용합니다.
- 경쟁사 상품 URL 직접 조회/크롤링 기능은 삭제되었습니다.
- 네이버 API는 `discountedPrice`가 있으면 할인가를, 없으면 `salePrice`를 사용합니다.

### 우리 상품 설정
기존 `검색 규칙`과 `상품 ID 규칙`을 하나로 합친 화면입니다.

우리 상품은 다음 순서로 찾습니다.
1. **상품 ID를 먼저 확인**합니다.
2. 상품 ID가 없거나 해당 ID로 상품을 찾지 못하면 **검색어로 다시 찾습니다.**
3. 둘 다 매칭되지 않으면 우리 가격은 빈칸으로 표시됩니다.

상품 ID에는 채널 상품번호, 원상품번호 또는 판매자 관리코드를 사용할 수 있습니다.

### 경쟁사 가격 입력
아래처럼 여러 상품을 한 번에 붙여넣을 수 있습니다.

```text
*로케트
우리 - 40,000
그린팜 - 55,000
야채왕 - 55,000
야채이야기 - 55,000
쉐프의정원 - 33,000
```

- `우리 - 가격`은 저장하지 않고 무시합니다. 우리 가격은 API에서 가져옵니다.
- 입력한 경쟁사 가격만 수정되고, 적지 않은 기존 가격은 그대로 유지됩니다.
- `야채이야기 -`처럼 가격을 비우면 해당 저장 가격을 삭제합니다.
- 매일 Cron이 실행되어도 경쟁사 가격을 새로 조회하거나 덮어쓰지 않습니다.

### 가격 규칙
- `mul`: 곱하기
- `add`: 더하기
- `sub`: 빼기
- `set`: 고정값
- `rate`: 비율 적용
- 경쟁사 수동 가격은 사용자가 입력한 최종 비교 금액을 그대로 사용합니다.

### 자동 실행
- 웹에서 `지금 실행`을 누르면 우리 가격을 API에서 새로 가져온 뒤 저장된 경쟁사 가격과 비교합니다.
- 매일 08:30 Cron도 같은 방식으로 실행되며 결과를 텔레그램으로 발송합니다.
- Cron 실행으로 경쟁사 수동 저장 가격은 변경되지 않습니다.
"""
)


st.info('Render Cron은 UTC 22:50으로 설정되어 있으며, 한국시간 기준 매일 오전 7시 50분에 자동 실행됩니다.')
